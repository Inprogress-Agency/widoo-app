/**
 * A route planned by a user (E-06), then followed (E-07) and closed (E-15). The route is frozen in
 * `route_revision_snapshot` (`PlannedRouteSnapshot` of `@widoo/shared`): a route unpublished,
 * edited or deleted afterwards stays readable here. Personal data, erased with the account; no
 * personal note (D-029). Completed Go count by route and by user (`route_id`, `user_id`, `status`).
 */
export const plannedRoutes = pgTable(
  'planned_routes',
  {
    id: id(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** Null once the route is deleted: the snapshot keeps what was planned. */
    routeId: uuid('route_id').references(() => routes.id, { onDelete: 'set null' }),
    routeRevisionSnapshot: jsonb('route_revision_snapshot').notNull(),
    startsAt: timestamp('starts_at', { withTimezone: true }).notNull(),
    status: plannedRouteStatus('status').notNull().default('planned'),
    /** `RouteTimeline` of `startsAt`, recomputed when it changes. */
    timeline: jsonb('timeline').notNull(),
    /** Step ids of the bookings ticked in « À préparer ». */
    checklist: jsonb('checklist').$type<string[]>().notNull().default([]),
    /** « Terminer la sortie », or the automatic closing at 4:00 the next day. */
    completedAt: timestamp('completed_at', { withTimezone: true }),
    /** Set when the Go is completed or stopped; `auto` for the job of 4:00 (D-033). */
    closedBy: plannedRouteCloser('closed_by'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index('planned_routes_user_starts_idx').on(t.userId, t.startsAt),
    index('planned_routes_route_status_idx').on(t.routeId, t.status),
    // One Go at a time (E-07): another one is stopped before this one starts.
    uniqueIndex('planned_routes_one_in_progress_idx')
      .on(t.userId)
      .where(sql`${t.status} = 'in_progress'`),
    check(
      'planned_routes_closed_by_check',
      sql`${t.closedBy} is null or ${t.status} in ('completed', 'stopped')`,
    ),
    check(
      'planned_routes_completed_at_check',
      sql`${t.completedAt} is null or ${t.status} = 'completed'`,
    ),
  ],
);

/**
 * Progress of each step of a planned route during the Go (E-07), one row per step of the snapshot.
 * `step_id` is the id in the snapshot, not a foreign key: editing the route rewrites its steps,
 * the planning keeps its own. A skipped step is not done (D-033).
 */
export const plannedSteps = pgTable(
  'planned_steps',
  {
    plannedRouteId: uuid('planned_route_id')
      .notNull()
      .references(() => plannedRoutes.id, { onDelete: 'cascade' }),
    stepId: uuid('step_id').notNull(),
    position: smallint('position').notNull(),
    /** « J'y suis » (D-029). */
    arrivedAt: timestamp('arrived_at', { withTimezone: true }),
    /** « Étape suivante »: « Fait à 10:22 » in the timeline of E-07. */
    doneAt: timestamp('done_at', { withTimezone: true }),
    /** « Passer cette étape » (D-033). */
    skippedAt: timestamp('skipped_at', { withTimezone: true }),
  },
  (t) => [
    primaryKey({ name: 'planned_steps_pkey', columns: [t.plannedRouteId, t.stepId] }),
    unique('planned_steps_route_position_unique').on(t.plannedRouteId, t.position),
    check(
      'planned_steps_done_or_skipped_check',
      sql`${t.doneAt} is null or ${t.skippedAt} is null`,
    ),
  ],
);

