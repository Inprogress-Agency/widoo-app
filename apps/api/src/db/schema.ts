/**
 * Answers of Mapbox Directions by trip (Orchestration › Transitions), read again instead of asking
 * twice. A point is its coordinates rounded to 5 decimals, stored times 100 000 as integers, so
 * that a key compares exactly. Written only while `MAPBOX_DIRECTIONS_CACHE_DAYS` is above 0, the
 * terms of Mapbox forbidding by default to store Directions results; a row past `expires_at` is
 * never read. Moving a place deletes the trips from and to its former point.
 */
export const directionCache = pgTable(
  'direction_cache',
  {
    profile: directionsProfile('profile').notNull(),
    fromLatE5: integer('from_lat_e5').notNull(),
    fromLngE5: integer('from_lng_e5').notNull(),
    toLatE5: integer('to_lat_e5').notNull(),
    toLngE5: integer('to_lng_e5').notNull(),
    distanceM: integer('distance_m').notNull(),
    durationS: integer('duration_s').notNull(),
    /** Route along the streets, encoded polyline (precision 5), for the map. */
    geometry: text('geometry').notNull(),
    createdAt: createdAt(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
  },
  (t) => [
    primaryKey({
      name: 'direction_cache_pkey',
      columns: [t.profile, t.fromLatE5, t.fromLngE5, t.toLatE5, t.toLngE5],
    }),
    index('direction_cache_from_idx').on(t.fromLatE5, t.fromLngE5),
    index('direction_cache_to_idx').on(t.toLatE5, t.toLngE5),
    check('direction_cache_measures_check', sql`${t.distanceM} >= 0 and ${t.durationS} >= 0`),
  ],
);

/**
 * A report of a route from its fiche (E-05, D-056), or opened by the API for a low rating (D-087),
 * then decided by the team in A-03. Never shown to the author. Personal data, erased with the
 * reporter's account. One report by user and by route over 7 days: `createRouteReport` holds the
 * rule, on the index `(route_id, user_id, created_at)` that `myReport` of `GET /routes/:id` reads.
 * `step_id` is not a foreign key, like `planned_steps.step_id`: editing a route rewrites its
 * steps, ids kept; the API checks it belongs to the route when the report is written.
 */
export const routeReports = pgTable(
  'route_reports',
  {
    id: id(),
    routeId: uuid('route_id')
      .notNull()
      .references(() => routes.id, { onDelete: 'cascade' }),
    /** The reporter; null for `low_rating` only, which has none. */
    userId: uuid('user_id').references(() => users.id, { onDelete: 'cascade' }),
    reason: routeReportReason('reason').notNull(),
    /** The step of the place for `place_changed`, null for any other reason. */
    stepId: uuid('step_id'),
    /** Null or not blank, 80 characters at most; read by the team, never published. */
    comment: text('comment'),
    status: reportStatus('status').notNull().default('open'),
    /** The member of the team who decided; null once their account is purged. */
    reviewedBy: uuid('reviewed_by').references(() => users.id, { onDelete: 'set null' }),
    reviewedAt: timestamp('reviewed_at', { withTimezone: true }),
    createdAt: createdAt(),
  },
  (t) => [
    index('route_reports_route_user_idx').on(t.routeId, t.userId, t.createdAt),
    index('route_reports_open_idx')
      .on(t.createdAt)
      .where(sql`${t.status} = 'open'`),
    // A low rating opens one report at a time per route (D-087).
    uniqueIndex('route_reports_one_open_low_rating_idx')
      .on(t.routeId)
      .where(sql`${t.reason} = '${sql.raw(systemRouteReportReason)}' and ${t.status} = 'open'`),
    check(
      'route_reports_reporter_check',
      sql`(${t.userId} is null) = (${t.reason} = '${sql.raw(systemRouteReportReason)}')`,
    ),
    check(
      'route_reports_step_check',
      sql`(${t.stepId} is not null) = ${isOneOf(t.reason, routeReportStepReasons)}`,
    ),
    check(
      'route_reports_comment_check',
      sql`${t.comment} is null or (${isOneOf(t.reason, routeReportCommentReasons)} and btrim(${t.comment}) <> '' and ${isAtMost(t.comment, routeReportCommentMaxLength)})`,
    ),
    check(
      'route_reports_comment_required_check',
      sql`${t.comment} is not null or not ${isOneOf(t.reason, routeReportCommentRequiredReasons)}`,
    ),
    check('route_reports_review_check', sql`(${t.status} = 'open') = (${t.reviewedAt} is null)`),
  ],
);

