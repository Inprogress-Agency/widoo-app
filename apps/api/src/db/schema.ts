/** Position of an anecdote or a featured route on the profile: 1 to 3. */
const isProfileSlot = (position: AnyPgColumn): SQL =>
  sql`${position} between 1 and ${sql.raw(String(profileSlots))}`;

/** Text of at most `maxLength` characters, as `plainText` of `@widoo/shared` bounds it. */
const isAtMost = (column: AnyPgColumn, maxLength: number): SQL =>
  sql`char_length(${column}) <= ${sql.raw(String(maxLength))}`;

/**
 * `column <@ ARRAY[...]`: every element of a `text[]` column is a key of the taxonomy. Keys are
 * snake_case constants (tested in `shared`), so inlining them is safe.
 */
/** `column in (...)` over keys of a taxonomy (snake_case constants, safe to inline). */
function isOneOf(column: AnyPgColumn, keys: readonly string[]): SQL {
  return sql`(${column} in (${sql.raw(keys.map((key) => `'${key}'`).join(', '))}))`;
}

function onlyKeysOf(column: AnyPgColumn, keys: readonly string[]): SQL {
  const list = keys.map((key) => `'${key}'`).join(', ');
  return sql`${column} <@ ARRAY[${sql.raw(list)}]::text[]`;
}

